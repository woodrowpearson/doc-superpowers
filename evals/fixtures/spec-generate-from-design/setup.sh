#!/usr/bin/env bash
# Fixture for eval "spec-generate-from-design": a Python service with an
# existing doc index (so new specs go through add-entry, not build-index), no
# docs/specs/ yet (bootstrap), and the design doc the prompt names. One section
# names a module (`auth.rbac`), not a path: the spec's code_refs must be the
# file that holds it.
. "$(dirname "$0")/../lib.sh"
fx_init "$0"

fx_write pyproject.toml <<'EOF'
[project]
name = "accounts"
version = "0.1.0"
EOF
fx_write src/app.py <<'EOF'
from auth import oauth, session, rbac
EOF
fx_write src/auth/oauth.py <<'EOF'
def callback(code, verifier):
    """Exchange an authorization code (PKCE) for tokens."""
EOF
fx_write src/auth/session.py <<'EOF'
SESSION_TTL_HOURS = 24
EOF
fx_write src/auth/rbac.py <<'EOF'
ROLES = ("admin", "member", "viewer")
EOF
fx_write docs/guides/getting-started.md <<'EOF'
<!-- Generated by doc-superpowers -->

# Getting Started

Install with `pip install -e .`.
EOF
fx_write docs/superpowers/specs/2026-03-14-user-auth-design.md <<'EOF'
# User Auth — Design

## OAuth flow

Sign-in goes through Google OAuth 2.0, authorization-code flow with PKCE.
`src/auth/oauth.py` handles the callback and the token exchange.

## Session management

Sessions are server-side with a 24 h sliding expiry, stored by `src/auth/session.py`.

## Role-based access control

Three roles — `admin`, `member`, `viewer` — checked by the `auth.rbac` module
before every handler.
EOF
fx_commit "feat: accounts service and user-auth design"
printf 'docs/guides/getting-started.md:pyproject.toml:guide\n' | dt build-index >/dev/null
fx_commit "docs: index"

fx_expect "an index with entries exists (new specs must go to add-entry)" \
  test "$(jq '.docs | length' docs/.doc-index.json)" -ge 1
fx_expect "docs/specs/ does not exist yet (bootstrap)" test ! -e docs/specs
fx_expect "the design doc has no Generated Specs section yet" \
  sh -c '! grep -q "^## Generated Specs" docs/superpowers/specs/2026-03-14-user-auth-design.md'
