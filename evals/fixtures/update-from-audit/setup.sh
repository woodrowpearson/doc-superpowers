const db = require('../db');
exports.route = async (req, res) => {
  if (req.method === 'GET' && req.url === '/orders') return res.end(JSON.stringify(await db.list()));
  if (req.method === 'POST' && req.url === '/orders') {
    let body = '';
    for await (const chunk of req) body += chunk;
    await db.add(JSON.parse(body));
    res.statusCode = 201;
    return res.end();
  }
  res.statusCode = 404;
  res.end();
};
EOF
